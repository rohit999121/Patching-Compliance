USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS SCCM_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS SCCM_DB;

CREATE SCHEMA IF NOT EXISTS SCCM_DB.RAW;
CREATE SCHEMA IF NOT EXISTS SCCM_DB.CORE;
CREATE SCHEMA IF NOT EXISTS SCCM_DB.MART;
CREATE SCHEMA IF NOT EXISTS SCCM_DB.DO;
CREATE SCHEMA IF NOT EXISTS SCCM_DB.ETL;

CREATE OR REPLACE FILE FORMAT RAW.FF_CSV
  TYPE                           = CSV
  FIELD_DELIMITER                = ','
  SKIP_HEADER                    = 1
  FIELD_OPTIONALLY_ENCLOSED_BY   = '"'
  NULL_IF                        = ('')                       -- empty field  -> NULL
  EMPTY_FIELD_AS_NULL            = TRUE
  DATE_FORMAT                    = 'YYYY-MM-DD'
  TIMESTAMP_FORMAT               = 'YYYY-MM-DD HH24:MI:SS.FF3'
  ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;  

CREATE OR REPLACE STAGE RAW.STG_SCCM FILE_FORMAT = RAW.FF_CSV

LIST @RAW.STG_SCCM