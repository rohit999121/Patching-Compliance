USE WAREHOUSE SCCM_WH; USE DATABASE SCCM_DB;

-- 5.1  Reload RAW from the stage (full refresh). New extract = upload new files to @RAW.STG_SCCM, then run this.
CREATE OR REPLACE PROCEDURE ETL.SP_LOAD_RAW()
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
BEGIN
  TRUNCATE TABLE RAW.SERVER_INVENTORY;
  COPY INTO RAW.SERVER_INVENTORY FROM @RAW.STG_SCCM PATTERN = '.*ServerInventory.*' ON_ERROR = 'ABORT_STATEMENT' FORCE = TRUE;

  TRUNCATE TABLE RAW.PATCHING_REPORT;
  COPY INTO RAW.PATCHING_REPORT FROM @RAW.STG_SCCM PATTERN = '.*PatchingReport.*' ON_ERROR = 'ABORT_STATEMENT' FORCE = TRUE;

  TRUNCATE TABLE RAW.PATCH_HISTORY;
  COPY INTO RAW.PATCH_HISTORY FROM @RAW.STG_SCCM PATTERN = '.*PatchHistory.*' ON_ERROR = 'ABORT_STATEMENT' FORCE = TRUE;

  TRUNCATE TABLE RAW.VULNERABILITY_MAPPING;
  COPY INTO RAW.VULNERABILITY_MAPPING FROM @RAW.STG_SCCM PATTERN = '.*VulnerabilityMapping.*' ON_ERROR = 'ABORT_STATEMENT' FORCE = TRUE;

  RETURN 'RAW load complete';
END;
$$;

-- 5.2  Master procedure with run id, logging and error handling
CREATE OR REPLACE PROCEDURE ETL.SP_RUN_PIPELINE()
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
DECLARE
  v_run_id VARCHAR DEFAULT UUID_STRING();
  v_fail   NUMBER  DEFAULT 0;
BEGIN
  INSERT INTO DO.ETL_RUN_LOG (RUN_ID, STEP, STATUS, MESSAGE) SELECT :v_run_id, 'PIPELINE', 'STARTED', NULL;

  CALL ETL.SP_LOAD_RAW();
  INSERT INTO DO.ETL_RUN_LOG (RUN_ID, STEP, STATUS, MESSAGE) SELECT :v_run_id, 'LOAD_RAW', 'DONE', NULL;

  CALL ETL.SP_BUILD_CORE();
  INSERT INTO DO.ETL_RUN_LOG (RUN_ID, STEP, STATUS, MESSAGE) SELECT :v_run_id, 'BUILD_CORE', 'DONE', NULL;

  CALL DO.SP_RUN_DO_CHECKS(:v_run_id);
  SELECT COUNT(*) INTO :v_fail FROM DO.CHECK_RESULTS WHERE RUN_ID = :v_run_id AND STATUS = 'FAIL';

  INSERT INTO DO.ETL_RUN_LOG (RUN_ID, STEP, STATUS, MESSAGE)
  SELECT :v_run_id, 'PIPELINE',
         IFF(:v_fail = 0, 'SUCCESS', 'FINISHED_WITH_DO_FAILURES'),
         'Failed DO checks: ' || :v_fail;

  RETURN 'Run ' || v_run_id || ' finished. Failed DO checks: ' || v_fail;

EXCEPTION
  WHEN OTHER THEN
    INSERT INTO DO.ETL_RUN_LOG (RUN_ID, STEP, STATUS, MESSAGE) SELECT :v_run_id, 'PIPELINE', 'FAILED', :SQLERRM;
    RETURN 'Pipeline FAILED: ' || SQLERRM;
END;
$$;

-- 5.3  Run the whole pipeline and read the log
CALL ETL.SP_RUN_PIPELINE();

SELECT * FROM DO.ETL_RUN_LOG ORDER BY LOG_TS DESC LIMIT 20;
SELECT * FROM DO.VW_DO_LATEST_RUN ORDER BY STATUS, TABLE_NAME;

