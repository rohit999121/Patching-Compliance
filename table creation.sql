COPY INTO RAW.PATCH_HISTORY    FROM @RAW.STG_SCCM PATTERN = '.*PatchHistory.*'    VALIDATION_MODE = 'RETURN_ERRORS';
COPY INTO RAW.VULNERABILITY_MAPPING FROM @RAW.STG_SCCM PATTERN = '.*VulnerabilityMapping.*' VALIDATION_MODE = 'RETURN_ERRORS';

