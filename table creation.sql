CREATE OR REPLACE TABLE RAW.SERVER_INVENTORY (
  ServerID VARCHAR(20), ServerName VARCHAR(50), FQDN VARCHAR(200), IPAddress VARCHAR(20),
  Environment VARCHAR(30), BusinessUnit VARCHAR(100), ApplicationName VARCHAR(100),
  ApplicationOwner VARCHAR(100), ServerOwner VARCHAR(100), SupportTeam VARCHAR(100),
  Location VARCHAR(50), DataCenter VARCHAR(50), OperatingSystem VARCHAR(60), OSVersion VARCHAR(50),
  CPUCount NUMBER(5,0), MemoryGB NUMBER(6,0), DiskSpaceGB NUMBER(8,0),
  ServerCriticality VARCHAR(20), ServerType VARCHAR(30), VirtualizationPlatform VARCHAR(50),
  BuildDate DATE, CurrentStatus VARCHAR(30), CreatedDate TIMESTAMP_NTZ, LastModifiedDate TIMESTAMP_NTZ,
  DQ_Flags VARCHAR(500)
);

CREATE OR REPLACE TABLE RAW.PATCHING_REPORT (
  RecordID NUMBER(10,0), ServerID VARCHAR(20), ServerName VARCHAR(50), KBNumber VARCHAR(20),
  PatchTitle VARCHAR(300), PatchCategory VARCHAR(50), Severity VARCHAR(20), PatchStatus VARCHAR(30),
  ComplianceStatus VARCHAR(30), DeploymentStatus VARCHAR(40), PatchReleaseDate DATE,
  PatchInstalledDate TIMESTAMP_NTZ, RebootRequired NUMBER(1,0), LastScanDate TIMESTAMP_NTZ,
  DaysSincePatch NUMBER(6,0), DeploymentName VARCHAR(60), DeploymentDeadline TIMESTAMP_NTZ,
  PatchSource VARCHAR(30), CreatedDate TIMESTAMP_NTZ, LastModifiedDate TIMESTAMP_NTZ,
  DaysToInstall NUMBER(6,0), DQ_Flags VARCHAR(500)
);

CREATE OR REPLACE TABLE RAW.PATCH_HISTORY (
  HistoryID NUMBER(10,0), ServerID VARCHAR(20), KBNumber VARCHAR(20), PatchMonth NUMBER(2,0),
  PatchYear NUMBER(4,0), DeploymentCycle VARCHAR(30), PatchStatus VARCHAR(30), DeploymentStatus VARCHAR(40),
  PatchInstalledDate TIMESTAMP_NTZ, DeploymentDurationMinutes NUMBER(6,0), RebootRequired NUMBER(1,0),
  PatchFailureReason VARCHAR(100), DaysToCompliance NUMBER(6,0), CreatedDate TIMESTAMP_NTZ,
  LastModifiedDate TIMESTAMP_NTZ, DQ_Flags VARCHAR(500)
);

CREATE OR REPLACE TABLE RAW.VULNERABILITY_MAPPING (
  KBNumber VARCHAR(20), CVEID VARCHAR(30), CVSSScore NUMBER(3,1), RiskRating VARCHAR(20),
  ExploitAvailable VARCHAR(10), Vendor VARCHAR(50), VulnerabilityCategory VARCHAR(60),
  PublishedDate DATE, UpdatedDate DATE, DQ_Flags VARCHAR(500)
);

